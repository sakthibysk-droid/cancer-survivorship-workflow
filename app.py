import streamlit as st
import sqlite3
import pandas as pd
from datetime import date, datetime

st.set_page_config(
    page_title="Cancer Survivorship Workflow",
    page_icon="🩺",
    layout="wide"
)

# Database setup
conn = sqlite3.connect(
    "survivorship.db",
    check_same_thread=False
)

conn.execute("""
CREATE TABLE IF NOT EXISTS patients (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    patient_code TEXT UNIQUE,
    cancer_group TEXT,
    nurse TEXT
)
""")

conn.execute("""
CREATE TABLE IF NOT EXISTS followups (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    patient_code TEXT,
    call_date TEXT,
    status TEXT
)
""")

conn.execute("""
CREATE TABLE IF NOT EXISTS audit (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    action TEXT,
    timestamp TEXT
)
""")
conn.commit()


def log_action(action):
    conn.execute(
        "INSERT INTO audit (action, timestamp) VALUES (?, ?)",
        (action, datetime.now().isoformat(timespec="seconds"))
    )
    conn.commit()


st.sidebar.title("Survivorship Care")
page = st.sidebar.radio(
    "Navigation",
    [
        "Dashboard",
        "Patient Registration",
        "Call Scheduling",
        "Symptom Assessment",
        "Audit Log"
    ]
)

st.title("Cancer Survivorship Workflow Assistant")
st.caption("Administrative workflow support with clinician oversight")

if page == "Dashboard":
    patients = pd.read_sql_query(
        "SELECT * FROM patients", conn
    )
    calls = pd.read_sql_query(
        "SELECT * FROM followups", conn
    )

    c1, c2 = st.columns(2)
    c1.metric("Registered Patients", len(patients))
    c2.metric("Follow-up Calls", len(calls))

    st.subheader("Patient Registry")
    st.dataframe(patients, use_container_width=True)

elif page == "Patient Registration":
    st.subheader("Register Patient")

    with st.form("patient_form"):
        code = st.text_input("Pseudonymous Patient Code")
        cancer = st.selectbox(
            "Cancer Group",
            ["Breast", "Colorectal", "Lung",
             "Gynaecologic", "Other"]
        )
        nurse = st.text_input("Assigned Nurse")
        submitted = st.form_submit_button("Save Patient")

    if submitted:
        if not code.strip():
            st.error("Enter a patient code.")
        else:
            try:
                conn.execute(
                    """INSERT INTO patients
                    (patient_code, cancer_group, nurse)
                    VALUES (?, ?, ?)""",
                    (code.strip(), cancer, nurse.strip())
                )
                conn.commit()
                log_action("Patient record created")
                st.success("Patient registered.")
            except sqlite3.IntegrityError:
                st.error("This patient code already exists.")

elif page == "Call Scheduling":
    patients = pd.read_sql_query(
        "SELECT patient_code FROM patients", conn
    )

    if patients.empty:
        st.info("Register a patient first.")
    else:
        with st.form("call_form"):
            code = st.selectbox(
                "Patient",
                patients["patient_code"].tolist()
            )
            call_date = st.date_input(
                "Follow-up Date", value=date.today()
            )
            status = st.selectbox(
                "Status",
                ["Scheduled", "Completed",
                 "Missed", "Reschedule Requested"]
            )
            submitted = st.form_submit_button("Save Follow-up")

        if submitted:
            conn.execute(
                """INSERT INTO followups
                (patient_code, call_date, status)
                VALUES (?, ?, ?)""",
                (code, call_date.isoformat(), status)
            )
            conn.commit()
            log_action("Follow-up record created")
            st.success("Follow-up saved.")

    st.subheader("Scheduled Follow-ups")
    st.dataframe(
        pd.read_sql_query(
            "SELECT * FROM followups ORDER BY call_date", conn
        ),
        use_container_width=True
    )

elif page == "Symptom Assessment":
    patients = pd.read_sql_query(
        "SELECT patient_code FROM patients", conn
    )

    if patients.empty:
        st.info("Register a patient first.")
    else:
        with st.form("symptom_form"):
            code = st.selectbox(
                "Patient",
                patients["patient_code"].tolist()
            )
            pain = st.slider("Pain severity (0–10)", 0, 10, 0)
            fatigue = st.slider(
                "Fatigue severity (0–10)", 0, 10, 0
            )
            breathlessness = st.slider(
                "Breathlessness severity (0–10)", 0, 10, 0
            )
            submitted = st.form_submit_button(
                "Evaluate Review Rules"
            )

        if submitted:
            flags = []
            if pain >= 7:
                flags.append("Pain threshold reached")
            if fatigue >= 8:
                flags.append("Fatigue threshold reached")
            if breathlessness >= 7:
                flags.append("Breathlessness threshold reached")

            log_action("Symptom assessment performed")

            if flags:
                st.warning(
                    "Review flags generated. Clinician assessment is required."
                )
                for flag in flags:
                    st.write(f"- {flag}")
            else:
                st.success("No configured thresholds were reached.")

            st.info(
                "These example thresholds are placeholders, "
                "not validated clinical guidance. Replace them "
                "with approved clinical rules before real use."
            )

elif page == "Audit Log":
    st.subheader("System Activity")
    logs = pd.read_sql_query(
        "SELECT * FROM audit ORDER BY id DESC", conn
    )
    st.dataframe(logs, use_container_width=True)
    st.download_button(
        "Download Audit Log",
        logs.to_csv(index=False),
        file_name="audit_log.csv",
        mime="text/csv"
    )